export function getChannelIcon(iconName: string, className?: string) {
  switch (iconName) {
    case 'feishu':
      return <FeishuIcon className={className} />;
    case 'telegram':
      return <TelegramIcon className={className} />;
    case 'slack':
      return <SlackIcon className={className} />;
    case 'wechat':
      return <WeComIcon className={className} />;
    case 'dingtalk':
      return <DingTalkIcon className={className} />;
    case 'webhook':
      return <WebhookIcon className={className} />;
    default:
      return <MessageSquare className={className} />;
  }
}
